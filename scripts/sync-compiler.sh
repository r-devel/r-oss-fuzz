#!/bin/bash
#
# Regenerate features/0001-compiler-native-byte-code-compiler.patch from the
# upstream pull request that adds R's byte-code compiler in C.
#
# Usage: scripts/sync-compiler.sh [--check | --force]
#
#   (no option)  rewrite the patch if the pull request's head has moved
#   --check      only compare; exit 1 if the patch is behind the head
#   --force      rewrite the patch even if it records the current head
#
# Exit status: 0 up to date or rewritten, 1 behind (--check), 2 error.
# Needs gh, authenticated or with GH_TOKEN set; the pull request is public.
# Run the patch checks afterwards (README, "Continuous integration"):
# R_PATCH_ONLY=1 R_PATCH_STRICT=1 ./ossfuzz.sh against a trunk checkout.
set -euo pipefail

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
upstream_repo=r-devel/r-svn
upstream_pr=463
patch_file=$repo/features/0001-compiler-native-byte-code-compiler.patch

# doc/NEWS.Rd changes almost daily upstream, so its hunk would stop applying
# long before the code does, and the fuzzed R has no use for the entry.
exclude_paths="doc/NEWS.Rd"

die() {
    echo "sync-compiler.sh: $*" >&2
    exit 2
}

mode=sync
case "${1:-}" in
    "") ;;
    --check) mode=check ;;
    --force) mode=force ;;
    *) die "unknown option '$1' (expected --check or --force)" ;;
esac

command -v gh >/dev/null || die "needs gh (https://cli.github.com)"

pr_head() {
    gh pr view "$upstream_pr" -R "$upstream_repo" \
        --json state,headRefOid --jq '.state + " " + .headRefOid'
}

info=$(pr_head) || die "cannot read $upstream_repo#$upstream_pr"
read -r state head <<< "$info"
if [ "$state" != OPEN ]; then
    die "$upstream_repo#$upstream_pr is $state. If it landed, patches-apply" \
        "reports the patch as ALREADY APPLIED and it should be deleted," \
        "together with instrumentation/0007; otherwise decide whether to keep" \
        "carrying it before syncing."
fi

recorded=
if [ -f "$patch_file" ]; then
    recorded=$(sed -n 's/^Upstream head: \([0-9a-f]*\)$/\1/p' "$patch_file")
fi

if [ "$recorded" = "$head" ] && [ "$mode" != force ]; then
    echo "sync-compiler.sh: up to date with $upstream_repo#$upstream_pr at $head"
    exit 0
fi
if [ "$mode" = check ]; then
    echo "sync-compiler.sh: ${recorded:-<no patch>} is behind $upstream_repo#$upstream_pr at $head" >&2
    exit 1
fi

tmp=$(mktemp "${TMPDIR:-/tmp}/sync-compiler.XXXXXX")
trap 'rm -f "$tmp" "$tmp.diff"' EXIT

gh pr diff "$upstream_pr" -R "$upstream_repo" --color=never > "$tmp.diff"

# The diff and the head are two requests; a push between them would record
# the wrong head.
info=$(pr_head) || die "cannot read $upstream_repo#$upstream_pr"
read -r _ head_after <<< "$info"
[ "$head_after" = "$head" ] || die "the pull request moved to $head_after while syncing; re-run"

grep -q '^diff --git a/src/main/bccompile\.c ' "$tmp.diff" ||
    die "the diff of $upstream_repo#$upstream_pr has no src/main/bccompile.c"

cat > "$tmp" <<EOF
R's byte-code compiler in C (src/main/bccompile.c), carried so that the
eval target compiles its inputs in C rather than through cmp.R.

The eval target byte-compiles every top-level expression before running
it (docs/eval.md).  cmp.R is R code, and compiling an input costs far
more than running it: in a strict-barrier build without sanitizers,
over the eval seeds, compilation is 97-100% of each input's compile and
eval time, and bccompile.c compiles the same expressions 53x faster
into identical byte-code.  compiler::compile() and the JIT use it
whenever it is built in, so the harness needs no change, and if this
patch stops applying they fall back to cmp.R.

Neither a fix nor instrumentation: an upstream proposal that has not
landed.  A crash whose stack is inside bccompile.c is a bug in this
carried change, not in R; fix it in the pull request and re-sync rather
than reporting it to R.  instrumentation/0007 adapts it to the eval
harness's allowlist frame.

Upstream status: r-devel/r-svn PR #$upstream_pr, R Bugzilla 19297 (Wishlist).
Generated by scripts/sync-compiler.sh from the pull request's diff,
without $exclude_paths.  Do not edit by hand; re-run the script.

Upstream head: $head

EOF

# Drop each excluded file's section, from its "diff --git" line up to the
# next one.
awk -v exclude="$exclude_paths" '
    BEGIN { n = split(exclude, paths, " ") }
    /^diff --git / {
        skip = 0
        for (i = 1; i <= n; i++)
            if ($3 == "a/" paths[i])
                skip = 1
    }
    !skip { print }
' "$tmp.diff" >> "$tmp"

mkdir -p "$(dirname "$patch_file")"
mv "$tmp" "$patch_file"

files=$(grep -c '^diff --git ' "$patch_file")
echo "sync-compiler.sh: ${recorded:-<no patch>} -> $head ($files files) in ${patch_file#"$repo"/}"
